#!/usr/bin/env python3
"""Upload Hazard Index scores (a dryrun.py CSV) to the hosted (production) public.ml_scores table, as model
'hazard_index', next to the other models' rows (migration 20261018020000_ml_scores_per_model, docs/ML_SCORES_BRIEF.md).

`python push.py [CSV]` only writes the SQL file next to the CSV. With `--apply` it also:
  1. checks the Supabase CLI and the linked project, that ml_scores has the `model` column (without it an upsert
     would overwrite the other models' rows), that the scores are less than 24 h old, and that every plant exists;
  2. prints a preview, including the other models already in ml_scores;
  3. asks for the linked project ref to be typed (or `--confirm <ref>`); anything else applies nothing;
  4. runs `supabase db query --linked -f <sql>`, reads the hazard_index rows back, and records <csv stem>.applied.json.
`--clear --apply` deletes only the hazard_index rows.

The same safety flow as models/mud-trafficability/stram/push.py; the small CLI helpers are copied, not imported,
so the two model folders stay independent.

compute_site_risk takes max(highest fresh ML score, hazard subscores); a score stops counting 36 h (now) or 48 h
(tomorrow) after it was pushed, or when it is cleared.

Usage
  python push.py                                   # newest artifacts/dryrun/ml_scores_*.csv -> .push.sql
  python push.py artifacts/dryrun/ml_scores_20261018T042429Z_for20261018.csv --apply
  python push.py --clear --apply
Exit codes: 0 ok, 1 refused or failed (nothing applied unless the message says so).
"""
from __future__ import annotations

import argparse
import collections
import csv
import json
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

from hazidx import paths

MODEL = "hazard_index"
STALE_HOURS = 24.0
HORIZONS = ("now", "tomorrow")
_VERSION = re.compile(r"^hazidx-[0-9A-Za-z.+_-]+$")
SETUP = ("From the repo root:\n"
         "  install the CLI (https://supabase.com/docs/guides/local-development/cli/getting-started)\n"
         "  supabase login\n"
         "  supabase link --project-ref <project-ref>")
EFFECTS = (
    "Production effects:\n"
    "  - site risk becomes max(highest fresh ML score, hazard subscores) + crew term, for every crew at each site\n"
    "  - where this score is the largest input, top_driver reads \"ML hazard index <score>\"\n"
    "  - the 'tomorrow' score feeds the 6 PM briefing's predicted_risk and forecast warnings\n"
    "  - other models' rows are not touched; no alerts are raised; scores stop counting after 36 h (now) / 48 h (tomorrow)\n"
    "  - risk updates on the next evaluate-all-sites run (every 5 min)\n"
    "  Undo: run.sh push --clear --apply")


class ApplyError(RuntimeError):
    """A refusal or failure. Nothing has been applied when this is raised before the apply step."""


def latest_csv() -> Path:
    files = sorted(paths.DRYRUN.glob("ml_scores_*.csv"), key=lambda p: p.stat().st_mtime)
    if not files:
        raise ApplyError("No scores in artifacts/dryrun/. Run: run.sh score")
    return files[-1]


def read_scores(path: Path) -> list[dict]:
    """The CSV rows, checked: plant ids are digits, horizons now/tomorrow, scores 0-10, one row per plant and horizon."""
    with open(path, newline="", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    if not rows:
        raise ApplyError(f"{path.name} has no rows")
    seen = set()
    for r in rows:
        key = (r["eia_plant_id"], r["horizon"])
        if not r["eia_plant_id"].isdigit() or r["horizon"] not in HORIZONS or key in seen:
            raise ApplyError(f"{path.name}: bad or repeated row {key}")
        if not 0 <= float(r["score"]) <= 10 or not _VERSION.match(r["model_version"]):
            raise ApplyError(f"{path.name}: bad score or model_version in row {key}")
        seen.add(key)
    return rows


def push_sql(rows: list[dict], source: str) -> str:
    values = ",\n    ".join(f"('{r['eia_plant_id']}', '{r['horizon']}', {float(r['score']):.1f}, '{r['model_version']}')"
                           for r in sorted(rows, key=lambda r: (r["eia_plant_id"], r["horizon"])))
    return (f"-- Generated by models/hazard-index/push.py from {source} at {_now_iso()}.\n"
            f"-- Targets the HOSTED project. {len(rows)} rows, model '{MODEL}'. Other models' rows are not touched.\n"
            "select public.upsert_ml_scores(coalesce((\n"
            "  select jsonb_agg(jsonb_build_object('site_id', s.id, 'horizon', v.horizon, 'score', v.score,\n"
            f"                                         'model', '{MODEL}', 'model_version', v.model_version))\n"
            f"  from (values\n    {values}\n  ) as v(eia, horizon, score, model_version)\n"
            "  join public.sites s on s.eia_plant_id = v.eia\n"
            "), '[]'::jsonb));\n")


def clear_sql() -> str:
    return (f"-- Generated by models/hazard-index/push.py at {_now_iso()}. Targets the HOSTED project.\n"
            f"delete from public.ml_scores where model = '{MODEL}';\n")


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------------------------------------------------------------------------------------------- CLI helpers

def _run(args: list[str]) -> subprocess.CompletedProcess:
    """Every Supabase CLI call goes through here (tests replace it)."""
    return subprocess.run(args, cwd=paths.REPO, capture_output=True, text=True, timeout=300)


def supabase_cli() -> str | None:
    return shutil.which("supabase")


def linked_project_ref() -> str | None:
    p = paths.REPO / "supabase" / ".temp" / "project-ref"
    ref = p.read_text().strip() if p.exists() else ""
    return ref or None


def _rows(stdout: str) -> list[dict]:
    """Rows from `supabase db query --output-format json`, whichever envelope this CLI version uses."""
    data = json.loads(stdout)
    for key in ("rows", "data", "result", "results"):
        if isinstance(data, dict) and key in data:
            data = data[key]
    if isinstance(data, list) and data and isinstance(data[0], list):  # one result set per statement
        data = data[-1]
    if not isinstance(data, list) or not all(isinstance(r, dict) for r in data):
        raise ApplyError(f"unexpected query output: {stdout[:300]}")
    return data


def query(cli: str, sql: str) -> list[dict]:
    """A read query against the linked project."""
    cp = _run([cli, "db", "query", "--linked", "--workdir", str(paths.REPO), "--output-format", "json", sql])
    if cp.returncode != 0:
        raise ApplyError(f"query failed: {(cp.stderr or cp.stdout).strip()[:500]}")
    return _rows(cp.stdout)


def _ask_tty(prompt: str) -> str:
    if not sys.stdin.isatty():
        raise ApplyError("No confirmation given. Re-run in a terminal, or pass --confirm <project-ref>.")
    return input(prompt)


# ---------------------------------------------------------------------------------------------- apply

def age_hours(rows: list[dict], now: datetime | None = None) -> float:
    run_at = datetime.strptime(rows[0]["run_at_utc"], "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    return ((now or datetime.now(timezone.utc)) - run_at).total_seconds() / 3600.0


def preview(path: Path, ref: str, rows: list[dict], others: list[dict]) -> str:
    lines = [f"Target: production project {ref} (linked)",
             f"Scores: {path.name}, forecast {rows[0]['run_at_utc']}, model {rows[0]['model_version']}",
             f"Rows: {len(rows)} as model '{MODEL}'"]
    for h in HORIZONS:
        hr = [r for r in rows if r["horizon"] == h]
        if hr:
            vals = [float(r["score"]) for r in hr]
            dates = dict(collections.Counter(r["local_date"] for r in hr))
            lines.append(f"  {h:8s} {len(hr)} plants, local dates {dates}, min {min(vals):.1f} max {max(vals):.1f}, "
                         f"at >= 3: {sum(v >= 3 for v in vals)}, at >= 7.5: {sum(v >= 7.5 for v in vals)}")
    top = sorted(rows, key=lambda r: -float(r["score"]))[:10]
    lines.append("  Highest: " + ", ".join(f"{r['site_name']} {r['horizon']} {float(r['score']):.1f}" for r in top))
    lines.append("Already in ml_scores: " + ("; ".join(f"{o['model']} {o['horizon']}: {o['n']} rows, {o['lo']:.1f}-{o['hi']:.1f}"
                                                      for o in others) if others else "nothing"))
    return "\n".join(lines + [EFFECTS])


def apply(csv_path: Path | None, clear: bool = False, confirm: str | None = None, allow_stale: bool = False,
          ask: Callable[[str], str] = _ask_tty, out=print, now: datetime | None = None) -> dict:
    """Preflight, preview, confirm, apply, read back. Returns the record written next to the SQL file."""
    cli = supabase_cli()
    if not cli:
        raise ApplyError("Supabase CLI not found on PATH.\n" + SETUP)
    ref = linked_project_ref()
    if not ref:
        raise ApplyError("This checkout is not linked to a Supabase project (supabase/.temp/project-ref).\n" + SETUP)
    has_model = query(cli, "select count(*)::int as n from information_schema.columns where table_schema='public' "
                           "and table_name='ml_scores' and column_name='model'")
    if not has_model or has_model[0]["n"] != 1:
        raise ApplyError("Production ml_scores has no `model` column, so this push would overwrite the other models' "
                         "rows. Apply migration 20261018020000_ml_scores_per_model first. Nothing applied.")
    others = query(cli, "select model, horizon, count(*)::int as n, min(score)::float as lo, max(score)::float as hi "
                        "from public.ml_scores group by 1, 2 order by 1, 2")
    if clear:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        sql_path = paths.DRYRUN / f"ml_scores_clear_{stamp}.sql"
        sql_path.parent.mkdir(parents=True, exist_ok=True)
        sql_path.write_text(clear_sql())
        n = sum(o["n"] for o in others if o["model"] == MODEL)
        out(f"Target: production project {ref} (linked)\nDeletes {n} ml_scores rows with model '{MODEL}'. "
            "Other models' rows stay. Site risk updates on the next 5-min run.")
        expected, rows = 0, []
    else:
        rows = read_scores(csv_path)
        age = age_hours(rows, now)
        if age > STALE_HOURS and not allow_stale:
            raise ApplyError(f"{csv_path.name} is {age:.0f} h old. Scores never expire in production, so run "
                             "`run.sh score` first (or pass --allow-stale).")
        eias = sorted({r["eia_plant_id"] for r in rows})
        found = {r["eia_plant_id"] for r in query(cli, "select eia_plant_id from public.sites where eia_plant_id in ("
                                                       + ",".join(f"'{e}'" for e in eias) + ")")}
        missing = [e for e in eias if e not in found]
        if missing:
            raise ApplyError(f"{len(missing)} plants are not in production public.sites: {missing}. Nothing applied.")
        sql_path = csv_path.with_suffix(".push.sql")
        sql_path.write_text(push_sql(rows, csv_path.name))
        out(preview(csv_path, ref, rows, others))
        expected = len(rows)

    typed = confirm if confirm is not None else ask(f"Type the project ref ({ref}) to apply to production: ")
    if typed.strip() != ref:
        raise ApplyError("Confirmation did not match the linked project ref. Nothing applied.")

    cp = _run([cli, "db", "query", "--linked", "--workdir", str(paths.REPO), "-f", str(sql_path)])
    if cp.returncode != 0:
        raise ApplyError(f"apply failed: {(cp.stderr or cp.stdout).strip()[:500]}")

    back = query(cli, "select horizon, count(*)::int as n, min(score)::float as lo, max(score)::float as hi "
                      f"from public.ml_scores where model = '{MODEL}' group by horizon order by horizon")
    after = query(cli, "select model, count(*)::int as n from public.ml_scores group by 1 order by 1")
    got = sum(r["n"] for r in back)
    record = {"applied_at": _now_iso(), "project_ref": ref, "action": "clear" if clear else "push",
              "source": None if clear else csv_path.name, "sql": sql_path.name, "rows_expected": expected,
              "rows_read_back": got, "read_back": back, "models_after": after}
    for r in back:
        vals = [float(x["score"]) for x in rows if x["horizon"] == r["horizon"]]
        if not vals or r["n"] != len(vals) or abs(r["lo"] - min(vals)) > 0.05 or abs(r["hi"] - max(vals)) > 0.05:
            record["mismatch"] = True
    (sql_path.parent / (sql_path.name.split(".")[0] + (".cleared.json" if clear else ".applied.json"))).write_text(
        json.dumps(record, indent=1))
    if got != expected or record.get("mismatch"):
        raise ApplyError(f"Applied, but the read-back does not match: {back} (expected {expected} rows). "
                         "Check production before relying on it.")
    out(f"Applied to {ref}: {got} '{MODEL}' rows read back {back}. All models now: {after}.")
    return record


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Upload Hazard Index scores to production ml_scores (model 'hazard_index')")
    ap.add_argument("csv", nargs="?", type=Path, help="a dryrun.py CSV (default: the newest in artifacts/dryrun/)")
    ap.add_argument("--apply", action="store_true", help="send it to the linked project (asks for confirmation)")
    ap.add_argument("--clear", action="store_true", help="delete the hazard_index rows instead")
    ap.add_argument("--confirm", help="the linked project ref, instead of typing it at the prompt")
    ap.add_argument("--allow-stale", action="store_true", dest="allow_stale")
    args = ap.parse_args(argv)
    try:
        if args.apply:
            apply(None if args.clear else (paths.user_path(args.csv) if args.csv else latest_csv()), clear=args.clear, confirm=args.confirm,
                  allow_stale=args.allow_stale)
            return 0
        if args.clear:
            path = paths.DRYRUN / f"ml_scores_clear_{datetime.now(timezone.utc):%Y%m%dT%H%M%SZ}.sql"
            path.write_text(clear_sql())
        else:
            src = paths.user_path(args.csv) if args.csv else latest_csv()
            path = src.with_suffix(".push.sql")
            path.write_text(push_sql(read_scores(src), src.name))
        print(f"wrote {path}\nApply with confirmation: run.sh push {'--clear ' if args.clear else ''}"
              f"{'' if args.clear else (str(args.csv) + ' ' if args.csv else '')}--apply")
        return 0
    except (ApplyError, FileNotFoundError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
