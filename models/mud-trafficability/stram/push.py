"""SQL for the hosted (production) ml_scores table, and the confirmed apply step.

`python -m stram push` only writes the SQL file. `python -m stram push --apply` also:
  1. checks the Supabase CLI and the linked project, refuses runs older than 24 h, and checks that every site exists;
  2. prints a preview of what will change;
  3. asks for the linked project ref to be typed (or `--confirm <ref>`); anything else applies nothing;
  4. runs `supabase db query --linked -f <sql>`, reads the rows back, and records applied.json in the run folder.

compute_site_risk takes max(ML score, subscores) and has no staleness check, so pushed scores raise site risk for
every crew at the site until they are overwritten or cleared (`push --clear --apply`).
"""
from __future__ import annotations

import collections
import csv
import json
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable

from . import config as C

HORIZONS = {"now": "now", "d1": "tomorrow"}  # model horizon -> ml_scores.horizon
METRICS = {"max": "score", "p90": "score_p90"}
DEFAULT_METRIC = "p90"  # chosen for production 2026-10-18; max put 38/60 sites at 6.5 every day
STALE_HOURS = 24.0
SETUP = ("From the repo root:\n"
         "  install the CLI (https://supabase.com/docs/guides/local-development/cli/getting-started)\n"
         "  supabase login\n"
         "  supabase link --project-ref <project-ref>")
EFFECTS = (
    "Production effects:\n"
    "  - site risk becomes max(ML score, hazard subscores) + crew term, for every crew at each site\n"
    "  - where the ML score is largest, top_driver reads \"ML hazard index <score>\"\n"
    "  - the 'tomorrow' score feeds the 6 PM briefing's predicted_risk\n"
    "  - no alerts are raised; scores persist until overwritten or cleared (no expiry)\n"
    "  - risk updates on the next evaluate-all-sites run (every 5 min)\n"
    "  Undo: python -m stram push --clear --apply")


class ApplyError(RuntimeError):
    """A refusal or failure. Nothing has been applied when this is raised before the apply step."""


def site_scores(run_dir: Path, metric: str = DEFAULT_METRIC) -> dict[tuple[str, str], float]:
    """(eia, ml_scores horizon) -> worst score over machine classes at the default pass count."""
    col = METRICS[metric]
    out: dict[tuple[str, str], float] = {}
    with open(run_dir / "sites.csv", newline="") as f:
        for r in csv.DictReader(f):
            if r["horizon"] in HORIZONS and int(r["passes"]) == C.DEFAULT_PASSES:
                key = (r["eia"], HORIZONS[r["horizon"]])
                out[key] = max(out.get(key, 0.0), min(10.0, round(float(r[col]), 1)))
    return out


def write_push_sql(run_dir: Path, clear: bool = False, metric: str = DEFAULT_METRIC) -> tuple[Path, int]:
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    head = (f"-- Generated by `python -m stram push` from {run_dir.name} at {stamp}.\n"
            f"-- {C.LABEL}\n-- Targets the HOSTED project. Site risk picks this up on the next evaluate-all-sites run (5 min).\n")
    if clear:
        path = run_dir / "ml_scores_clear.sql"
        path.write_text(head + f"delete from public.ml_scores where model_version = '{C.MODEL_VERSION}';\n")
        return path, 0
    scores = site_scores(run_dir, metric)
    for (eia, _h) in scores:
        if not eia.isdigit():
            raise ValueError(f"unexpected EIA id {eia!r}")
    values = ",\n    ".join(f"('{eia}', '{h}', {s:.1f})" for (eia, h), s in sorted(scores.items()))
    sql = (head + f"-- Score: {metric} over route segments, worst machine class, {C.DEFAULT_PASSES} pass(es). "
           f"{len(scores)} rows.\n"
           "select public.upsert_ml_scores(coalesce((\n"
           "  select jsonb_agg(jsonb_build_object('site_id', s.id, 'horizon', v.horizon, 'score', v.score,\n"
           f"                                         'model_version', '{C.MODEL_VERSION}'))\n"
           f"  from (values\n    {values}\n  ) as v(eia, horizon, score)\n"
           "  join public.sites s on s.eia_plant_id = v.eia\n"
           "), '[]'::jsonb));\n")
    path = run_dir / "ml_scores_push.sql"
    path.write_text(sql)
    return path, len(scores)


# ---------------------------------------------------------------------------------------------- apply

def _run(args: list[str]) -> subprocess.CompletedProcess:
    """Every Supabase CLI call goes through here (tests replace it)."""
    return subprocess.run(args, cwd=C.REPO, capture_output=True, text=True, timeout=300)


def supabase_cli() -> str | None:
    return shutil.which("supabase")


def linked_project_ref() -> str | None:
    p = C.REPO / "supabase" / ".temp" / "project-ref"
    ref = p.read_text().strip() if p.exists() else ""
    return ref or None


def _rows(stdout: str) -> list[dict]:
    """Rows from `supabase db query --output-format json`, whichever envelope this CLI version uses."""
    data = json.loads(stdout)
    for key in ("rows", "data", "result", "results"):
        if isinstance(data, dict) and key in data:
            data = data[key]
    if isinstance(data, list) and data and isinstance(data[0], list):  # one result set per statement
        data = data[-1]
    if not isinstance(data, list) or not all(isinstance(r, dict) for r in data):
        raise ApplyError(f"unexpected query output: {stdout[:300]}")
    return data


def query(cli: str, sql: str) -> list[dict]:
    """A read query against the linked project."""
    cp = _run([cli, "db", "query", "--linked", "--workdir", str(C.REPO), "--output-format", "json", sql])
    if cp.returncode != 0:
        raise ApplyError(f"query failed: {(cp.stderr or cp.stdout).strip()[:500]}")
    return _rows(cp.stdout)


def run_age_hours(run_dir: Path, now: datetime | None = None) -> float:
    generated = datetime.fromisoformat(json.loads((run_dir / "run.json").read_text())["generated_at"])
    return ((now or datetime.now(timezone.utc)) - generated).total_seconds() / 3600.0


def preview(run_dir: Path, metric: str, ref: str, scores: dict[tuple[str, str], float], names: dict[str, str]) -> str:
    run = json.loads((run_dir / "run.json").read_text())
    lines = [f"Target: production project {ref} (linked)",
             f"Run: {run_dir.name}, generated {run['generated_at']}, model {C.MODEL_VERSION}",
             f"Metric: {metric}. Rows: {len(scores)} ({len({e for e, _ in scores})} sites x {sorted({h for _, h in scores})})"]
    for h in ("now", "tomorrow"):
        vals = [s for (e, hh), s in scores.items() if hh == h]
        if vals:
            dist = dict(sorted(collections.Counter(round(v) for v in vals).items()))
            lines.append(f"  {h:8s} min {min(vals):.1f}  max {max(vals):.1f}  sites at >= 6.5: {sum(v >= 6.5 for v in vals)}"
                         f"  (rounded counts {dist})")
    top = sorted(((s, e) for (e, h), s in scores.items() if h == "tomorrow"), reverse=True)[:10]
    lines.append("  Highest tomorrow: " + ", ".join(f"{names.get(e, e)} {s:.1f}" for s, e in top))
    return "\n".join(lines + [EFFECTS])


def _ask_tty(prompt: str) -> str:
    if not sys.stdin.isatty():
        raise ApplyError("No confirmation given. Re-run in a terminal, or pass --confirm <project-ref>.")
    return input(prompt)


def apply(run_dir: Path, metric: str = DEFAULT_METRIC, clear: bool = False, confirm: str | None = None,
          allow_stale: bool = False, ask: Callable[[str], str] = _ask_tty, out=print) -> dict:
    """Preflight, preview, confirm, apply, read back. Returns the record written to applied.json / cleared.json."""
    cli = supabase_cli()
    if not cli:
        raise ApplyError("Supabase CLI not found on PATH.\n" + SETUP)
    ref = linked_project_ref()
    if not ref:
        raise ApplyError("This checkout is not linked to a Supabase project (supabase/.temp/project-ref).\n" + SETUP)
    if not clear:
        age = run_age_hours(run_dir)
        if age > STALE_HOURS and not allow_stale:
            raise ApplyError(f"{run_dir.name} is {age:.0f} h old. Scores never expire in production, so run "
                             "`python -m stram forecast` first (or pass --allow-stale).")
    path, n = write_push_sql(run_dir, clear=clear, metric=metric)

    if clear:
        current = query(cli, f"select count(*)::int as n from public.ml_scores where model_version = '{C.MODEL_VERSION}'")
        out(f"Target: production project {ref} (linked)\nDeletes {current[0]['n']} ml_scores rows with "
            f"model_version {C.MODEL_VERSION}. Site risk falls back to the hazard subscores on the next 5-min run.")
        expected_rows = 0
    else:
        scores = site_scores(run_dir, metric)
        eias = sorted({e for e, _ in scores})
        found = {r["eia_plant_id"] for r in query(cli, "select eia_plant_id from public.sites where eia_plant_id in ("
                                                       + ",".join(f"'{e}'" for e in eias) + ")")}
        missing = [e for e in eias if e not in found]
        if missing:
            raise ApplyError(f"{len(missing)} sites are not in production public.sites: {missing}. Nothing applied.")
        names = {s["eia"]: s["name"] for s in json.loads((run_dir / "run.json").read_text())["sites"]}
        out(preview(run_dir, metric, ref, scores, names))
        expected_rows = n

    typed = confirm if confirm is not None else ask(f"Type the project ref ({ref}) to apply to production: ")
    if typed.strip() != ref:
        raise ApplyError("Confirmation did not match the linked project ref. Nothing applied.")

    cp = _run([cli, "db", "query", "--linked", "--workdir", str(C.REPO), "-f", str(path)])
    if cp.returncode != 0:
        raise ApplyError(f"apply failed: {(cp.stderr or cp.stdout).strip()[:500]}")

    back = query(cli, "select horizon, count(*)::int as n, min(score)::float as lo, max(score)::float as hi "
                      f"from public.ml_scores where model_version = '{C.MODEL_VERSION}' group by horizon order by horizon")
    got = sum(r["n"] for r in back)
    record = {"applied_at": datetime.now(timezone.utc).isoformat(timespec="seconds"), "project_ref": ref,
              "action": "clear" if clear else "push", "metric": None if clear else metric, "sql": path.name,
              "rows_expected": expected_rows, "rows_read_back": got, "read_back": back}
    if not clear:
        for r in back:
            vals = [s for (_e, h), s in scores.items() if h == r["horizon"]]
            if r["n"] != len(vals) or abs(r["lo"] - min(vals)) > 0.05 or abs(r["hi"] - max(vals)) > 0.05:
                record["mismatch"] = True
    (run_dir / ("cleared.json" if clear else "applied.json")).write_text(json.dumps(record, indent=1))
    if got != expected_rows or record.get("mismatch"):
        raise ApplyError(f"Applied, but the read-back does not match: {back} (expected {expected_rows} rows). "
                         "Check production before relying on it.")
    out(f"Applied to {ref}: {got} rows read back {back}. Recorded in {run_dir.name}/"
        f"{'cleared' if clear else 'applied'}.json.")
    return record
